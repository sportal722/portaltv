import assert from "node:assert/strict";
import { mock } from "node:test";
import { playbackRecovery } from "../lib/playback-recovery.ts";
mock.timers.enable({ apis: ["setTimeout"] });
const notices = [],
  calls = [];
const r = playbackRecovery((s) => notices.push(s));
r.network(() => calls.push("first"));
r.network(() => calls.push("duplicate"));
mock.timers.tick(999);
assert.equal(calls.length, 0);
mock.timers.tick(1);
assert.deepEqual(calls, ["first"]);
r.network(() => calls.push("second"));
mock.timers.tick(1999);
assert.equal(calls.length, 1);
mock.timers.tick(1);
assert.equal(calls.length, 2);
r.network(() => calls.push("third"));
mock.timers.tick(4000);
assert.equal(calls.length, 3);
r.network(() => calls.push("unbounded"));
mock.timers.tick(10000);
assert.equal(calls.length, 3);
assert.match(notices.at(-1), /sigue sin estar disponible/);
let media = 0;
r.media(() => media++);
r.media(() => media++);
assert.equal(media, 1);
assert.match(notices.at(-1), /recuperar el vídeo/);
const disposed = playbackRecovery(() => {});
disposed.network(() => calls.push("after dispose"));
disposed.stop();
mock.timers.tick(10000);
assert.equal(calls.length, 3);
disposed.media(() => media++);
assert.equal(media, 1);
mock.timers.reset();
console.log(
  "PASS: network retries 1/2/4s, deduplication, bounded attempts, one media recovery and disposal cancellation",
);
